"""Narrow, fail-closed OCSF IAM Authentication (class_uid=3002) adapter.

Only status_id 1/2 maps to successful/failed login. There is no arbitrary
mapping of unknown OCSF events to attack claims. Actor IDs use keyed HMAC.
"""
from __future__ import annotations
from collections.abc import Iterable
from dataclasses import asdict
import hashlib
import hmac
import json
from typing import Any
from .lab import Event, MAX_LINE_BYTES, MAX_LINES

OCSF_AUTHENTICATION_UID = 3002


def adapt_authentication(raw: dict[str, Any], salt: bytes) -> Event | None:
    """Map one OCSF authentication record, or skip unsupported outcomes/classes.

    A salt must be a high-entropy secret held locally. Repeated records for
    the same account remain joinable within the same study, but actor values
    do not contain the original username/UID.
    """
    if not isinstance(salt, bytes) or len(salt) < 16:
        raise ValueError("salt must contain at least 16 locally generated bytes")
    if not isinstance(raw, dict):
        raise ValueError("OCSF record must be an object")
    if type(raw.get("class_uid")) is not int or raw["class_uid"] != OCSF_AUTHENTICATION_UID:
        return None
    status = raw.get("status_id")
    if type(status) is not int or status not in (1, 2):
        return None
    milliseconds = raw.get("time")
    if type(milliseconds) is not int or not 0 <= milliseconds <= 4_102_444_800_000:
        raise ValueError("OCSF time must be valid epoch milliseconds")
    user = raw.get("user")
    if not isinstance(user, dict):
        raise ValueError("OCSF authentication requires a user object")
    uid = user.get("uid") or user.get("name")
    if not isinstance(uid, str) or not 1 <= len(uid) <= 512:
        raise ValueError("OCSF authentication user must contain bounded uid/name")
    actor = "hmac:" + hmac.new(salt, uid.encode("utf-8"), hashlib.sha256).hexdigest()[:32]
    remote = raw.get("is_remote", False)
    if type(remote) is not bool:
        raise ValueError("OCSF is_remote must be a boolean")
    return Event(ts=milliseconds // 1000, actor=actor,
                 kind="login_success" if status == 1 else "login_failed",
                 source="ocsf-iam-authentication", remote=remote, truth=False)


def map_jsonl(lines: Iterable[str], salt: bytes) -> tuple[list[Event], dict[str, int]]:
    mapped: list[Event] = []
    counts = {"input": 0, "mapped": 0, "unsupported": 0}
    for i, line in enumerate(lines, 1):
        if i > MAX_LINES or len(line.encode("utf-8")) > MAX_LINE_BYTES:
            raise ValueError("OCSF input size limit reached")
        if not line.strip():
            continue
        counts["input"] += 1
        try:
            event = adapt_authentication(json.loads(line), salt)
        except (json.JSONDecodeError, TypeError, ValueError) as exc:
            raise ValueError(f"invalid OCSF input line {i}: {exc}") from exc
        if event is None:
            counts["unsupported"] += 1
        else:
            mapped.append(event)
            counts["mapped"] += 1
    mapped.sort(key=lambda x: x.ts)
    return mapped, counts


def as_jsonl(events: Iterable[Event]) -> str:
    return "".join(json.dumps(asdict(e), sort_keys=True) + "\n" for e in events)
